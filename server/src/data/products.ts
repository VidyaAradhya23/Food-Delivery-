import type { Product } from '../types/index.js';
import { getDummyImagesForProduct } from './dummy-images.js';

function dish(overrides: Partial<Product> & Pick<Product, 'id' | 'slug' | 'title' | 'brand' | 'gender' | 'categoryPath' | 'mrp' | 'price' | 'isVeg'>): Product {
  const generatedImages = overrides.images && overrides.images.length > 0
    ? overrides.images
    : getDummyImagesForProduct(overrides.id, overrides.gender, overrides.categoryPath);

  const colors = (overrides.colors && overrides.colors.length > 0
    ? overrides.colors
    : [{ name: 'Standard Spice', hex: '#ff4722', images: [] }, { name: 'Extra Spicy', hex: '#dc2626', images: [] }]
  ).map((c, idx) => ({
    ...c,
    images: c.images && c.images.length > 0 ? c.images : [generatedImages[idx % generatedImages.length] || generatedImages[0]],
  }));

  const cuisine = overrides.cuisine || overrides.categoryPath[0] || 'Specialty';
  const prepTime = overrides.prepTime || '20-25 mins';
  const portionSize = overrides.portionSize || 'Serves 1-2';

  return {
    discountPercent: Math.round(((overrides.mrp - overrides.price) / overrides.mrp) * 100),
    sizes: overrides.sizes || [
      { name: 'Regular', stock: 20 },
      { name: 'Large', stock: 15 },
      { name: 'Family Pack', stock: 10 },
    ],
    fabric: cuisine,
    fit: portionSize,
    pattern: overrides.isVeg ? 'Pure Veg' : 'Non-Veg',
    occasion: ['All Day', 'Dinner', 'Lunch'],
    rating: 4.5,
    ratingCount: 340,
    description: `Freshly prepared ${overrides.title} from ${overrides.brand}. Cooked to perfection using authentic ingredients and delivered hot & fresh to your doorstep.`,
    highlights: ['Freshly Cooked to Order', 'No Preservatives', '100% Contactless Delivery', 'Spill-Proof Eco Packaging'],
    careInstructions: ['Best consumed immediately while hot', 'Reheat in microwave for 45s if needed'],
    deliveryEstimateDays: 0,
    returnWindowDays: 0,
    tags: overrides.tags || ['popular'],
    createdAt: '2026-09-01T00:00:00Z',
    cuisine,
    prepTime,
    portionSize,
    calories: overrides.calories || 450,
    spiceLevel: overrides.spiceLevel || 'Medium',
    isBestseller: overrides.isBestseller || false,
    restaurantName: overrides.brand,
    restaurantId: overrides.brand.toLowerCase().replace(/[^a-z0-9]+/g, '-'),
    addOns: overrides.addOns || [
      { id: 'a1', name: 'Extra Dip / Chutney', price: 25 },
      { id: 'a2', name: 'Thums Up (250ml Can)', price: 40 },
      { id: 'a3', name: 'Extra Cheese / Butter', price: 35 },
    ],
    ...overrides,
    images: generatedImages,
    colors,
  };
}

